"""Human-readable H-04 Diff / Review Markdown views."""

from __future__ import annotations

import json
from collections.abc import Mapping
from typing import Any

from .diff import ObjectDiffReport, ResultReviewReport

REVIEW_MARKDOWN_VERSION = "1.0"


class DiffReviewMarkdownRenderer:
    """Pure renderer for H-04 structured reports."""

    def render_review(self, report: ResultReviewReport | Mapping[str, Any]) -> str:
        value = report.to_dict() if isinstance(report, ResultReviewReport) else dict(report)
        lines = [
            "<!-- SGOKB H-04 review preview: read-only, no approval side effect. -->",
            "# Object Result Review",
            "",
            "> **Read-only review material.** This preview does not Import, approve, reject, "
            "rebase, or mutate canonical Knowledge.",
            "",
            "## State",
            "",
            f"- Review state: **{self._inline(value.get('review_state', 'unknown'))}**",
            f"- Validation state: `{self._code(value.get('validation_state', 'unknown'))}`",
            f"- Receipt ID: `{self._code(value.get('receipt_id', ''))}`",
            f"- Package ID: `{self._code(value.get('package_id', ''))}`",
            f"- Object ID: `{self._code(value.get('object_id', ''))}`",
            f"- Base Version: `{self._code(value.get('base_version_id') or 'none')}`",
            f"- Current Version: `{self._code(value.get('current_version_id') or 'none')}`",
            f"- Result status: `{self._code(value.get('result_status') or 'unknown')}`",
        ]
        if value.get("imported_version_id"):
            lines.append(f"- Imported Version: `{self._code(value.get('imported_version_id'))}`")
            lines.append(
                "- Review acknowledged at Import: "
                + ("yes" if value.get("review_acknowledged") else "no")
            )

        lines.extend(["", "## Review reasons", ""])
        reasons = value.get("reasons") or []
        if not reasons:
            lines.append("_No review or blocking reasons._")
        else:
            for reason in reasons:
                severity = str(reason.get("severity", "attention")).upper()
                path = f" at `{self._code(reason['path'])}`" if reason.get("path") else ""
                lines.append(
                    f"- **{severity}** `{self._code(reason.get('code', 'reason'))}`{path}: "
                    f"{self._inline(reason.get('message', ''))}"
                )

        lines.extend(self._render_diff(value.get("diff") or {}))
        lines.extend(
            [
                "",
                "## Next action",
                "",
            ]
        )
        state = value.get("review_state")
        if state == "ready_to_import":
            lines.append("- Result is structurally ready for the explicit H-02 Import operation.")
        elif state == "review_required":
            lines.append(
                "- Review the highlighted changes. If accepted, run H-02 Import with explicit "
                "review acknowledgement."
            )
        elif state == "blocked":
            lines.append(
                "- Do not Import. Resolve the blocking validation/stale condition, normally by "
                "regenerating the Package / Result."
            )
        elif state == "imported":
            lines.append(
                "- This receipt has already been imported; use historical Version Diff as needed."
            )
        else:
            lines.append("- Complete H-01 Validation before authoritative Import decisions.")

        lines.extend(
            [
                "",
                "---",
                "",
                f"_Generated by SGOKB H-04 Review Renderer {REVIEW_MARKDOWN_VERSION}. "
                "Approval remains an explicit H-02 Import action._",
                "",
            ]
        )
        return "\n".join(lines)

    def render_diff(self, report: ObjectDiffReport | Mapping[str, Any]) -> str:
        value = report.to_dict() if isinstance(report, ObjectDiffReport) else dict(report)
        lines = [
            "<!-- SGOKB H-04 historical diff: derived read-only view. -->",
            "# Object Knowledge Diff",
            "",
            "> **Derived comparison.** Diff output is not canonical Knowledge and does not "
            "mutate Versions.",
        ]
        lines.extend(self._render_diff(value))
        lines.extend(
            [
                "",
                "---",
                "",
                f"_Generated by SGOKB H-04 Review Renderer {REVIEW_MARKDOWN_VERSION}._",
                "",
            ]
        )
        return "\n".join(lines)

    def _render_diff(self, diff: Mapping[str, Any]) -> list[str]:
        lines = [
            "",
            "## Diff",
            "",
            f"- Object ID: `{self._code(diff.get('object_id', ''))}`",
            f"- Before Version: `{self._code(diff.get('before_version_id') or 'none')}`",
            "- After: `"
            + self._code(diff.get("after_version_id") or diff.get("after_kind") or "candidate")
            + "`",
        ]
        destructive = diff.get("destructive_omissions") or []
        lines.extend(["", "### Destructive omissions", ""])
        if not destructive:
            lines.append("_None detected._")
        else:
            for item in destructive:
                lines.append(
                    f"- **{self._inline(item.get('section', 'knowledge'))}** / "
                    f"`{self._code(item.get('key', item.get('facet_id', 'item')))}`: "
                    f"{self._inline(item.get('change', 'removed'))}"
                )
                if item.get("before") is not None:
                    lines.append(f"  - Before: `{self._code(self._json(item['before']))}`")
                if item.get("after") is not None:
                    lines.append(f"  - After: `{self._code(self._json(item['after']))}`")

        changes = diff.get("changes") or {}
        for key, title in (
            ("summary_statements", "Summary statements"),
            ("facets", "Facets"),
            ("attributes", "Attributes"),
            ("relations", "Relations"),
        ):
            lines.extend(["", f"### {title}", ""])
            section = changes.get(key) or []
            if not section:
                lines.append("_No changes._")
            elif key == "facets":
                for item in section:
                    lines.extend(self._facet_change_lines(item))
            else:
                for item in section:
                    lines.extend(self._change_lines(item))

        lines.extend(["", "### Review metadata", ""])
        review = changes.get("review_metadata") or {}
        any_review_changes = False
        for collection, title in (
            ("conflicts", "Conflicts"),
            ("gaps", "Gaps"),
            ("unresolved_references", "Unresolved references"),
            ("registry_proposals", "Registry proposals"),
        ):
            items = review.get(collection) or []
            if not items:
                continue
            any_review_changes = True
            lines.extend([f"#### {title}", ""])
            for item in items:
                lines.extend(self._change_lines(item))
            lines.append("")
        if not any_review_changes:
            lines.append("_No review-metadata changes._")
        return lines

    def _facet_change_lines(self, item: Mapping[str, Any]) -> list[str]:
        lines = [
            f"- **{self._inline(item.get('change', 'modified').upper())}** "
            f"`{self._code(item.get('facet_id', ''))}`: "
            f"`{self._code(item.get('before_status'))}` → `{self._code(item.get('after_status'))}`"
        ]
        statements = item.get("statements") or []
        for statement in statements:
            lines.append(
                f"  - Statement **{self._inline(statement.get('change', '').upper())}** "
                f"`{self._code(statement.get('key', ''))}`"
            )
            if statement.get("before") is not None:
                lines.append(f"    - Before: `{self._code(self._json(statement['before']))}`")
            if statement.get("after") is not None:
                lines.append(f"    - After: `{self._code(self._json(statement['after']))}`")
        return lines

    def _change_lines(self, item: Mapping[str, Any]) -> list[str]:
        lines = [
            f"- **{self._inline(item.get('change', 'modified').upper())}** "
            f"`{self._code(item.get('key', ''))}`"
        ]
        if item.get("before") is not None:
            lines.append(f"  - Before: `{self._code(self._json(item['before']))}`")
        if item.get("after") is not None:
            lines.append(f"  - After: `{self._code(self._json(item['after']))}`")
        return lines

    @staticmethod
    def _json(value: Any) -> str:
        return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"))

    @staticmethod
    def _inline(value: Any) -> str:
        return str(value).replace("\r", " ").replace("\n", " ").replace("`", "\\`")

    @staticmethod
    def _code(value: Any) -> str:
        return str(value).replace("`", "ˋ").replace("\r", " ").replace("\n", " ")
